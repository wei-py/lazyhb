export function categories(kind: ProjectKind): Category[] {
  return structuredClone(definitions[kind]);
}
export function sensitive(path: string[]): boolean {
  return path.some((part) => /password|secret|token|privatekey/i.test(part));
}
export function inferredField(path: string[], value: unknown): Field {
  const kind: FieldKind =
    typeof value === "boolean"
      ? "boolean"
      : typeof value === "number"
        ? Number.isInteger(value)
          ? "integer"
          : "number"
        : value === null || typeof value === "object"
          ? "json"
          : "string";
  return {
    path,
    label: path.at(-1) ?? "",
    kind,
    description: "项目中已有的扩展字段；保留原值与类型。",
  };
}
export function categoryFields(
  category: Category,
  document: JsonDocument,
): Field[] {
  const fields = [...category.fields];
  const declared = new Set(fields.map((f) => JSON.stringify(f.path)));
  const append = (path: string[], value: unknown): void => {
    if (
      value !== null &&
      typeof value === "object" &&
      !Array.isArray(value) &&
      Object.keys(value).length
    ) {
      for (const [key, child] of Object.entries(value))
        append([...path, key], child);
    } else if (path.length && !declared.has(JSON.stringify(path))) {
      fields.push(inferredField(path, value));
      declared.add(JSON.stringify(path));
    }
  };
  const missing = Symbol();
  if (category.node !== null) {
    const value = document.get(category.node, missing);
    if (value !== missing) append(category.node, value);
  }
  return fields;
}
/** No permissions are inferred or removed. Supply explicit indices after user selection. */
export function disableModule(
  document: JsonDocument,
  field: Field,
  removePermissionIndices: readonly number[] = [],
): void {
  const original = document.text;
  try {
    const path = ["app-plus", "distribute", "android", "permissions"];
    const permissions = document.get(path);
    if (Array.isArray(permissions) && removePermissionIndices.length)
      document.set(
        path,
        permissions.filter((_, i) => !removePermissionIndices.includes(i)),
      );
    document.delete(field.path);
  } catch (error) {
    document.replaceSource(original);
    throw error;
  }
}
export function setField(
  document: JsonDocument,
  field: Field,
  value: unknown,
): void {
  if (field.choices?.length && !field.choices.includes(String(value)))
    throw new Error("值必须是：" + field.choices.join(", "));
  const original = document.text;
  try {
    if (field.kind === "module") {
      if (typeof value !== "boolean")
        throw new Error("Module value must be boolean");
      if (!value) disableModule(document, field);
      else {
        const existing = document.get(field.path);
        document.set(
          field.path,
          existing !== null &&
            typeof existing === "object" &&
            !Array.isArray(existing)
            ? existing
            : {},
        );
      }
    } else {
      document.set(field.path, value);
      if (JSON.stringify(field.path) === '["uni-app-x","vapor"]') {
        if (value === true) {
          document.set(["uni-app-x", "styleIsolationVersion"], "2");
          document.set(["uni-app-x", "vapor-render-target"], "bytecode");
        } else document.delete(["uni-app-x", "vapor-render-target"]);
      }
    }
  } catch (error) {
    document.replaceSource(original);
    throw error;
  }
}
